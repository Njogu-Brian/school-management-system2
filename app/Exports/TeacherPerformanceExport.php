<?php

namespace App\Exports;

use Maatwebsite\Excel\Concerns\FromArray;
use Maatwebsite\Excel\Concerns\WithTitle;

class TeacherPerformanceExport implements FromArray, WithTitle
{
    public function __construct(
        private readonly array $sheetPayload,
        private readonly string $title = 'Teacher Performance',
        private readonly string $generatedBy = 'System',
        private readonly ?string $schoolLine = null,
    ) {}

    public function title(): string
    {
        return mb_substr($this->title, 0, 31);
    }

    public function array(): array
    {
        $school = $this->schoolLine ?? setting('school_name', config('app.name', 'School'));
        $meta = $this->sheetPayload['meta'] ?? [];
        $prev = $meta['previous_term'] ?? null;
        $out = [
            [$school],
            ['Teacher Performance — '.$this->title],
            ['Printed '.now()->format('Y-m-d H:i').' | Generated by: '.$this->generatedBy],
            ['Scope: '.($meta['scope'] ?? 'class').' | Mode: '.($meta['mode'] ?? '')],
        ];
        if (is_array($prev)) {
            $out[] = ['Previous term: '.($prev['academic_year'] ?? '').' · '.($prev['term_name'] ?? '')];
        }
        $out[] = [];

        $categories = collect($this->sheetPayload['by_category'] ?? [])->values();
        if ($categories->isNotEmpty()) {
            foreach ($categories as $category) {
                $heading = trim(($category['label'] ?? 'Category').' — '.($category['detail'] ?? ''));
                $out[] = [$heading];
                $out[] = ['Teacher Rankings'];
                $out[] = ['Rank', 'Teacher', 'Subjects', 'Mean', 'Prev mean', 'Improvement'];
                foreach ($category['per_teacher'] ?? [] as $row) {
                    $out[] = [
                        $row['rank'] ?? null,
                        $row['teacher'] ?? 'Unassigned',
                        $row['subjects_count'] ?? null,
                        $row['mean_of_subject_means'] ?? null,
                        $row['prev_mean'] ?? null,
                        $row['improvement'] ?? null,
                    ];
                }

                $out[] = [];
                $out[] = ['Subject-by-Subject'];
                $out[] = ['Class', 'Subject', 'Teacher', 'Rank in subject', 'Mean', 'Prev mean', 'Improvement', 'Pass %', 'Count'];
                foreach ($category['per_subject_teacher'] ?? [] as $row) {
                    $out[] = [
                        $row['classroom'] ?? '',
                        $row['subject'] ?? '',
                        $row['teacher'] ?? 'Unassigned',
                        $row['rank_in_subject'] ?? null,
                        $row['mean'] ?? null,
                        $row['prev_mean'] ?? null,
                        $row['improvement'] ?? null,
                        $row['pass_rate'] ?? null,
                        $row['count'] ?? null,
                    ];
                }
                $out[] = [];
            }

            return $out;
        }

        if (! empty($this->sheetPayload['rows']) && (($meta['scope'] ?? '') === 'teacher')) {
            $summary = $this->sheetPayload['summary'] ?? [];
            $out[] = ['Teacher', $this->sheetPayload['teacher'] ?? ''];
            $out[] = ['Subjects', $summary['subjects_count'] ?? null];
            $out[] = ['Classes', $summary['classes_count'] ?? null];
            $out[] = ['Overall mean', $summary['mean_of_subject_means'] ?? null];
            $out[] = ['Previous mean', $summary['prev_mean'] ?? null];
            $out[] = ['Improvement', $summary['improvement'] ?? null];
            $out[] = [];
            $out[] = ['Section', 'Class', 'Subject', 'Mean', 'Prev mean', 'Improvement', 'Pass %', 'Count'];
            foreach ($this->sheetPayload['rows'] as $row) {
                $out[] = [
                    $row['category'] ?? '',
                    $row['classroom'] ?? '',
                    $row['subject'] ?? '',
                    $row['mean'] ?? null,
                    $row['prev_mean'] ?? null,
                    $row['improvement'] ?? null,
                    $row['pass_rate'] ?? null,
                    $row['count'] ?? null,
                ];
            }

            return $out;
        }

        $out[] = ['Teacher Rankings'];
        $out[] = ['Rank', 'Teacher', 'Subjects', 'Mean', 'Prev mean', 'Improvement'];
        foreach ($this->sheetPayload['per_teacher'] ?? [] as $row) {
            $out[] = [
                $row['rank'] ?? null,
                $row['teacher'] ?? 'Unassigned',
                $row['subjects_count'] ?? null,
                $row['mean_of_subject_means'] ?? null,
                $row['prev_mean'] ?? null,
                $row['improvement'] ?? null,
            ];
        }

        $out[] = [];
        $out[] = ['Subject-by-Subject'];
        $subjectRows = $this->sheetPayload['per_subject_teacher'] ?? $this->sheetPayload['per_subject'] ?? [];
        $hasRank = collect($subjectRows)->contains(fn ($r) => array_key_exists('rank_in_subject', $r));
        $hasClass = collect($subjectRows)->contains(fn ($r) => ! empty($r['classroom'] ?? null));
        $out[] = array_values(array_filter([
            $hasClass ? 'Class' : null,
            'Subject',
            'Teacher',
            $hasRank ? 'Rank in subject' : null,
            'Mean',
            'Prev mean',
            'Improvement',
            'Pass %',
            'Count',
        ], fn ($v) => $v !== null));

        foreach ($subjectRows as $row) {
            $line = [];
            if ($hasClass) {
                $line[] = $row['classroom'] ?? '';
            }
            $line[] = $row['subject'] ?? '';
            $line[] = $row['teacher'] ?? 'Unassigned';
            if ($hasRank) {
                $line[] = $row['rank_in_subject'] ?? null;
            }
            $line[] = $row['mean'] ?? null;
            $line[] = $row['prev_mean'] ?? null;
            $line[] = $row['improvement'] ?? null;
            $line[] = $row['pass_rate'] ?? null;
            $line[] = $row['count'] ?? null;
            $out[] = $line;
        }

        return $out;
    }
}
