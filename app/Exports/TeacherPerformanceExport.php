<?php

namespace App\Exports;

use Maatwebsite\Excel\Concerns\FromArray;
use Maatwebsite\Excel\Concerns\WithTitle;

class TeacherPerformanceExport implements FromArray, WithTitle
{
    public function __construct(
        private readonly array $payload,
        private readonly string $title = 'Teacher Performance',
        private readonly string $generatedBy = 'System',
        private readonly ?string $schoolLine = null,
    ) {}

    public function title(): string
    {
        return mb_substr($this->title, 0, 31);
    }

    public function array(): array
    {
        $school = $this->schoolLine ?? setting('school_name', config('app.name', 'School'));
        $meta = $this->payload['meta'] ?? [];
        $out = [
            [$school],
            ['Teacher Performance — '.$this->title],
            ['Printed '.now()->format('Y-m-d H:i').' | Generated by: '.$this->generatedBy],
            ['Scope: '.($meta['scope'] ?? 'class').' | Mode: '.($meta['mode'] ?? '')],
            [],
            ['Teacher Rankings'],
            ['Rank', 'Teacher', 'Subjects', 'Mean of subject means'],
        ];

        foreach ($this->payload['per_teacher'] ?? [] as $row) {
            $out[] = [
                $row['rank'] ?? null,
                $row['teacher'] ?? 'Unassigned',
                $row['subjects_count'] ?? null,
                $row['mean_of_subject_means'] ?? null,
            ];
        }

        $out[] = [];
        $out[] = ['Subject-by-Subject'];
        $subjectRows = $this->payload['per_subject_teacher'] ?? $this->payload['per_subject'] ?? [];
        $hasRank = collect($subjectRows)->contains(fn ($r) => array_key_exists('rank_in_subject', $r));
        $out[] = $hasRank
            ? ['Subject', 'Teacher', 'Rank in subject', 'Mean', 'Pass %', 'Count']
            : ['Subject', 'Teacher', 'Mean', 'Pass %', 'Count'];

        foreach ($subjectRows as $row) {
            $line = [
                $row['subject'] ?? '',
                $row['teacher'] ?? 'Unassigned',
            ];
            if ($hasRank) {
                $line[] = $row['rank_in_subject'] ?? null;
            }
            $line[] = $row['mean'] ?? null;
            $line[] = $row['pass_rate'] ?? null;
            $line[] = $row['count'] ?? null;
            $out[] = $line;
        }

        return $out;
    }
}
